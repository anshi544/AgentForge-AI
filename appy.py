with st.form("task_form"):
    task_title = st.text_input(
        "Task title",
        placeholder="Example: Prepare a Python learning roadmap"
    )

    task_description = st.text_area(
        "Describe your goal",
        placeholder="Explain what you want to accomplish and any requirements.",
        height=160
    )

    task_type = st.selectbox(
        "Workflow type",
        [
            "General Task",
            "Research and Report",
            "Coding and Debugging",
            "Study Planning",
            "Content Creation"
        ]
    )

    submitted = st.form_submit_button(
        "Create Task",
        type="primary"
    )

if submitted:
    if not task_title.strip() or not task_description.strip():
        st.error("Please enter both a task title and description.")
    else:
        task = {
            "id": len(st.session_state.task_history) + 1,
            "title": task_title.strip(),
            "description": task_description.strip(),
            "type": task_type,
            "status": "Pending",
            "result": None
        }

        st.session_state.task_history.append(task)
        st.session_state.active_task = task["id"]

        st.success("Task created successfully!")
        st.info(
            "The task is saved in this session. "
            "Agent execution will be added in the next development stage."
        )
